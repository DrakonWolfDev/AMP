"""Generate per-user Open With registration; never write the registry here."""

from pathlib import Path

from amp.folder_navigator import SUPPORTED_SUFFIXES


def registry_entries():
    def entry(key, name, value, flags="", kind="string"):
        return (
            f'Root: HKCU; Subkey: "{key}"; ValueType: {kind}; ValueName: "{name}"; ValueData: "{value}"; Tasks: fileassociations'
            + (f"; Flags: {flags}" if flags else "")
        )

    progid = "WolfForge.AMP.Media"
    classes = "Software\\Classes\\"
    capabilities = "Software\\WolfForge\\AMP\\Capabilities"
    lines = [
        "; Generated by tools.windows_associations. No extension defaults or UserChoice writes.",
        "[Registry]",
        entry(classes + progid, "", "AMP media file", "uninsdeletekey"),
        entry(classes + progid + "\\DefaultIcon", "", '""{app}\\AMP.exe"",0'),
        entry(classes + progid + "\\shell\\open\\command", "", '""{app}\\AMP.exe"" ""%1""'),
        entry(classes + "Applications\\AMP.exe", "FriendlyAppName", "AMP", "uninsdeletekey"),
        entry(
            classes + "Applications\\AMP.exe\\shell\\open\\command", "", '""{app}\\AMP.exe"" ""%1""'
        ),
        entry(capabilities, "ApplicationName", "AMP", "uninsdeletekey"),
        entry(capabilities, "ApplicationDescription", "Local images, video and music"),
        entry(capabilities, "ApplicationIcon", '""{app}\\AMP.exe"",0'),
        entry("Software\\RegisteredApplications", "AMP", capabilities, "uninsdeletevalue"),
    ]
    for suffix in sorted(SUPPORTED_SUFFIXES):
        lines.extend(
            (
                entry(classes + suffix + "\\OpenWithProgids", progid, "", "uninsdeletevalue"),
                entry(classes + "Applications\\AMP.exe\\SupportedTypes", suffix, ""),
                entry(capabilities + "\\FileAssociations", suffix, progid),
            )
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "packaging/windows/associations.iss"
    target.write_text(registry_entries(), encoding="utf-8")
